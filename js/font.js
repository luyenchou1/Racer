const FONT_ORDER = Object.keys(FONT_GLYPHS);
const FONT_INDEX = {};
FONT_ORDER.forEach((c, i) => { FONT_INDEX[c] = i; });

const Font = {
  atlases: {}, // colour -> canvas

  atlas(color) {
    let a = this.atlases[color];
    if (a) return a;
    const c = document.createElement('canvas');
    c.width = FONT_ORDER.length * (FONT_W + 1);
    c.height = FONT_H;
    const g = c.getContext('2d');
    g.fillStyle = color;
    FONT_ORDER.forEach((ch, i) => {
      const rows = FONT_GLYPHS[ch];
      for (let y = 0; y < FONT_H; y++) {
        const row = rows[y];
        for (let x = 0; x < FONT_W; x++) if (row[x] === '#') g.fillRect(i * (FONT_W + 1) + x, y, 1, 1);
      }
    });
    this.atlases[color] = c;
    return c;
  },

  // Normalise accented characters to the font's ASCII set.
  clean(str) {
    return String(str).toUpperCase()
      .replace(/[ÉÈÊ]/g, 'E').replace(/[ÀÂ]/g, 'A').replace(/[ÔÖ]/g, 'O').replace(/[ÙÛ]/g, 'U').replace(/Ç/g, 'C');
  },

  width(str, scale = 1) {
    return this.clean(str).length * (FONT_W + 1) * scale - scale;
  },

  // Draw text. align: 'left' | 'center' | 'right'. Optional shadow colour.
  draw(ctx, str, x, y, opts = {}) {
    const scale = opts.scale || 1;
    const color = opts.color || '#ffffff';
    const s = this.clean(str);
    const w = s.length * (FONT_W + 1) * scale - scale;
    let ox = x;
    if (opts.align === 'center') ox = Math.round(x - w / 2);
    else if (opts.align === 'right') ox = Math.round(x - w);
    if (opts.shadow) this._blit(ctx, s, ox + scale, y + scale, scale, this.atlas(opts.shadow));
    if (opts.outline) {
      const oa = this.atlas(opts.outline);
      this._blit(ctx, s, ox - scale, y, scale, oa);
      this._blit(ctx, s, ox + scale, y, scale, oa);
      this._blit(ctx, s, ox, y - scale, scale, oa);
      this._blit(ctx, s, ox, y + scale, scale, oa);
    }
    this._blit(ctx, s, ox, y, scale, this.atlas(color));
    return w;
  },

  _blit(ctx, s, x, y, scale, atlas) {
    const gw = FONT_W * scale;
    for (let i = 0; i < s.length; i++) {
      const idx = FONT_INDEX[s[i]];
      if (idx === undefined || s[i] === ' ') continue;
      ctx.drawImage(atlas, idx * (FONT_W + 1), 0, FONT_W, FONT_H, x + i * (FONT_W + 1) * scale, y, gw, FONT_H * scale);
    }
  },
};
